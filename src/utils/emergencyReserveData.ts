export interface EmergencyLoanRecord {
  id: string; // e.g. "LOAN-20260817-001"
  equipmentId: string;
  equipmentName: string;
  equipmentModel: string;
  equipmentSn: string;
  category: string;
  
  // 借用双方
  borrowingDepartment: string; // 借入科室 e.g. "急诊科", "重症医学科", "麻醉手术科"
  borrowerName: string; // 借用人/经办护士/医生
  borrowerPhone: string; // 经办电话
  borrowReason: string; // 借用事由 e.g. "急诊抢救突发群伤应急支持", "病区无创呼吸机临时增援"
  
  // 时间节点
  borrowTime: string; // 借出借用时间 YYYY-MM-DD HH:mm
  expectedReturnTime: string; // 预计归还时间 YYYY-MM-DD HH:mm
  actualReturnTime?: string; // 实际归还时间
  
  // 状态流转
  status: 'borrowed' | 'returned' | 'overdue'; // 借出在用 | 已归还入库 | 超期未还
  
  // 库管与质控核验
  approver: string; // 审批/出库经办人 e.g. "李强 (应急库管员)"
  dispatchLocation: string; // 出库地点 e.g. "医学工程保障中心应急库 1号机架"
  accessoriesIncluded: string[]; // 随附配件清点 e.g. ["电源线", "病人管路", "血氧探头", "转运支架"]
  qualityCheckPassed: boolean; // 出库前质控自检是否合格
  
  // 归还验收
  returnInspector?: string; // 归还验收工程师/库管员
  returnCondition?: 'intact' | 'needs_cleaning' | 'faulty'; // 完好归还 | 需消毒 | 故障报修
  notes?: string;
}

