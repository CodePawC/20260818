export const EMERGENCY_LOAN_STORAGE_KEY = 'hospital_emergency_loan_records_v1';

export function loadEmergencyLoans(): EmergencyLoanRecord[] {
  try {
    const saved = localStorage.getItem(EMERGENCY_LOAN_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // 自动补充合并科室借调样例
        const existingIds = new Set(parsed.map(r => r.id));
        const missing = INITIAL_EMERGENCY_LOANS.filter(r => !existingIds.has(r.id));
        if (missing.length > 0) {
          const merged = [...missing, ...parsed];
          saveEmergencyLoans(merged);
          return merged;
        }
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Failed to load emergency loans from localStorage', err);
  }
  return INITIAL_EMERGENCY_LOANS;
}

export function saveEmergencyLoans(records: EmergencyLoanRecord[]) {
  try {
    localStorage.setItem(EMERGENCY_LOAN_STORAGE_KEY, JSON.stringify(records));
  } catch (err) {
    console.warn('Failed to save emergency loans to localStorage', err);
  }
}
