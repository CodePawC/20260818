const COLLAB_ORDERS_STORAGE_KEY = 'med_equip_vendor_collab_orders_v1';
const PARTNERS_STORAGE_KEY = 'med_equip_partners_v1';

// 获取所有外协协同单
export function getVendorCollaborationOrders(): VendorCollaborationOrder[] {
  try {
    if (typeof window === 'undefined' || !window.localStorage) {
      return initialVendorCollaborationOrders;
    }
    const saved = localStorage.getItem(COLLAB_ORDERS_STORAGE_KEY);
    if (saved) {
      const parsed: VendorCollaborationOrder[] = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // 与主数据科室字典强制标准化对齐
        let hasUpdatedDept = false;
        const normalized = parsed.map(o => {
          const masterDept = getDepartmentMasterInfo(o.equipmentDept).department;
          if (masterDept && masterDept !== o.equipmentDept) {
            hasUpdatedDept = true;
            return { ...o, equipmentDept: masterDept };
          }
          return o;
        });

        const existingIds = new Set(normalized.map(o => o.id));
        const missing = initialVendorCollaborationOrders.filter(o => !existingIds.has(o.id));
        if (missing.length > 0 || hasUpdatedDept) {
          const merged = missing.length > 0 ? [...normalized, ...missing] : normalized;
          localStorage.setItem(COLLAB_ORDERS_STORAGE_KEY, JSON.stringify(merged));
          return merged;
        }
        return normalized;
      }
    }
  } catch (e) {
    console.error('Error loading vendor collaboration orders:', e);
  }
  return initialVendorCollaborationOrders;
}

// 保存所有外协协同单
export function saveVendorCollaborationOrders(orders: VendorCollaborationOrder[]): void {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      localStorage.setItem(COLLAB_ORDERS_STORAGE_KEY, JSON.stringify(orders));
    }
  } catch (e) {
    console.error('Error saving vendor collaboration orders:', e);
  }
}

// 获取合作单位列表
export function getPartnersList(): PartnerOrganization[] {
  try {
    if (typeof window === 'undefined' || !window.localStorage) {
      return DEFAULT_PARTNERS;
    }
    const saved = localStorage.getItem(PARTNERS_STORAGE_KEY);
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (e) {
    console.error('Error loading partners:', e);
  }
  return DEFAULT_PARTNERS;
}

// 保存合作单位列表并触发双向同步
export function savePartnersList(partners: PartnerOrganization[]): void {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      localStorage.setItem(PARTNERS_STORAGE_KEY, JSON.stringify(partners));
    }
  } catch (e) {
    console.error('Error saving partners:', e);
  }
}

/**
 * 双向同步：当外协协同单归档或发票核准时，自动同步更新【往来合作单位】中的统计信息：
 * 1. 累计维修台次 +1
 * 2. 累计结算金额累加
 * 3. 记录最新履约评价
 */
export function syncVendorCollaborationToPartner(order: VendorCollaborationOrder): void {
  const partners = getPartnersList();
  const index = partners.findIndex(p => p.id === order.vendorId);
  if (index === -1) return;

  const partner = { ...partners[index] };
  const finalPrice = order.finalNegotiatedPrice || order.quoteGrandTotal || 0;
  
  // 履约评分更新（若有临床好评）
  if (order.completionReport?.clinicalRating) {
    const currentRating = partner.cooperationRating || 4.8;
    const newRating = ((currentRating * 4 + order.completionReport.clinicalRating) / 5);
    partner.cooperationRating = parseFloat(newRating.toFixed(1));
  }

  // 记录最近动态台账与外协维修归档
  const recordNote = `【外协一案一档归档】工单: ${order.workOrderId}，设备: ${order.equipmentName}，结算金额: ¥${finalPrice.toLocaleString()}，发票号: ${order.invoiceRecord?.invoiceCode || "待抵扣"} (${new Date().toLocaleDateString()})。
`;
  partner.notes = recordNote + (partner.notes || "");

  partners[index] = partner;
  savePartnersList(partners);
}
